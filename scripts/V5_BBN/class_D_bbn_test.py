# =========================================================================
# 2. Hubble rate during BBN (standard radiation-dominated FRW)
# =========================================================================

def hubble_rate_BBN(T_MeV: float, g_star: float = 10.75) -> float:
    """Hubble rate H(T) during BBN in s^-1.

    H = 1.66 sqrt(g_*) T^2 / M_Planck  with T, M_Planck in energy units.

    For T = 1 MeV, g_* = 10.75 (photons + 3 nu species + e+/e-), one gets
    H ~ 1.13 s^-1, t = 1/(2H) ~ 0.44 s -- the standard FRW value.
    """
    M_PL_GEV = 2.435e18 * math.sqrt(8 * math.pi)  # reduced -> total Mp
    T_GeV = T_MeV * 1e-3
    # H in GeV : H = 1.66 sqrt(g_*) T^2 / M_pl_total
    H_GeV = 1.66 * math.sqrt(g_star) * T_GeV ** 2 / M_PL_GEV
    # Convert GeV -> s^-1 : 1 GeV = 1.519e24 s^-1
    return H_GeV * 1.519e24


def cosmic_time_BBN(T_MeV: float, g_star: float = 10.75) -> float:
    """Cosmic time t = 1/(2H) at temperature T (s)."""
    return 1.0 / (2.0 * hubble_rate_BBN(T_MeV, g_star=g_star))


# =========================================================================
# 3. V5 Class-D heavy-proton production rate (Vassiliev-suppressed)
# =========================================================================

# Vassiliev exponent for the heavy-proton entrelacs (Gen 5+, c_n eff ~ 20).
# V5 sec. 13.6.4 sigma_DM-N(c) ~ sigma_EM * alpha_EM^{c-18} with c = 20
# for a Gen-5 heavy proton.
C_VASSILIEV_HP = 20


def vassiliev_suppression_HP(c_n: int = C_VASSILIEV_HP) -> float:
    """Vassiliev suppression factor alpha_EM^{c_n} for HP production."""
    return ALPHA_EM ** c_n


def gamma_HP_production(T_MeV: float, c_n: int = C_VASSILIEV_HP,
                        g_star: float = 10.75) -> float:
    """V5 Class-D heavy-proton production rate (s^-1).

    Gamma_HP(T) = alpha_EM^{c_n} * H(T)
    (V5.17 cascade: production rate gated by Vassiliev penalty.)
    """
    return vassiliev_suppression_HP(c_n) * hubble_rate_BBN(T_MeV, g_star=g_star)


# =========================================================================
# 4. V5 Class-D abundance during BBN
# =========================================================================

# Heavy-proton lifetime (V5 sec. 13.7): tau_HP ~ 10^3 s for Gen-5 m_HP ~ 3 GeV
TAU_HP_S = 1.0e3
M_HP_GEV = (HEAVY_PROTON_GEV_LOW + HEAVY_PROTON_GEV_HIGH) / 2.0   # ~ 3.1 GeV


def n_HP_over_n_baryon(T_MeV: float, c_n: int = C_VASSILIEV_HP) -> float:
    """V5 Class-D HP abundance n_HP / n_baryon at temperature T.

    For quasi-equilibrium between production and decay :
        n_HP(T) = Gamma_HP(T) * tau_HP  (per unit volume of baryons)
    Normalised by the photon-to-baryon ratio (eta_Planck):
        n_HP / n_b = (Gamma_HP * tau_HP) / (eta * H * tau_universe)
                   ~ alpha_EM^{c_n}   (to leading order)

    We use the rigorous form
        n_HP / n_b = alpha_EM^{c_n} * (tau_HP / t_BBN(T))
    where t_BBN(T) = 1/(2H(T)).
    """
    t = cosmic_time_BBN(T_MeV)
    return vassiliev_suppression_HP(c_n) * (TAU_HP_S / t)


# =========================================================================
# 5. Delta N_eff contribution from HP plasma
# =========================================================================

def delta_N_eff_HP(T_MeV: float, c_n: int = C_VASSILIEV_HP) -> float:
    """Effective shift to N_eff from the HP plasma.

    HP rest mass m_HP ~ 3 GeV >> T_BBN ~ 1 MeV, so HPs are non-relativistic
    at BBN. Their contribution to N_eff is the rho_HP / rho_nu ratio, scaled
    by (T/m_HP)^{3/2} (Boltzmann tail).

        rho_HP = n_HP * m_HP * (3/2) (Boltzmann KE)
        rho_nu_1 = (7/8) * (4/11)^{4/3} * (pi^2 / 30) * T^4

    Delta N_eff = rho_HP / rho_nu_1 -- but rho_HP itself is suppressed by
    alpha_EM^{c_n} ~ 4e-43, so Delta N_eff << 1.
    """
    n_HP_over_n_b = n_HP_over_n_baryon(T_MeV, c_n=c_n)
    # n_b / T^3 ~ eta * n_gamma / T^3 ~ eta * 0.244
    n_b_over_T3 = ETA_PLANCK * 0.244
    n_HP_over_T3 = n_HP_over_n_b * n_b_over_T3
    # Boltzmann suppression for m_HP >> T : n_HP_eff ~ n_HP * exp(-m_HP/T)
    # For T = 1 MeV, m_HP = 3 GeV : exp(-3000) -> 0 numerically.
    # We do not include this multiplicative suppression here ; the Vassiliev
    # one already dwarfs everything. We treat the plasma as cold matter,
    # so its contribution to N_eff is set by (rho_HP / rho_nu_1) treated
    # as additional cold radiation (over-estimate).
    rho_nu_1_over_T4 = (7.0 / 8.0) * (4.0 / 11.0) ** (4.0 / 3.0) * (math.pi ** 2 / 30.0)
    rho_HP_over_T4 = n_HP_over_T3 * M_HP_GEV * 1e3   # to MeV
    # Treat as Delta N_eff = (rho_HP / rho_nu_1) on a per-flavour basis.
    return rho_HP_over_T4 / rho_nu_1_over_T4 / (T_MeV)


# =========================================================================
# 6. D/H shift from HP cascade-decay injection
# =========================================================================

def DH_shift_from_HP_decay(T_MeV: float = 0.07,
                           c_n: int = C_VASSILIEV_HP) -> float:
    """Estimated shift on D/H from HP cascade-decay during BBN.

    Each HP decay injects (p + n + gamma) symmetrically (V5.17 cascade -> SM
    thermal bath). The injection is :
        Delta(n/p) ~ 0  (symmetric)
        Delta(D/H) ~ n_HP / n_b
    because each HP that decays during BBN contributes at most one extra D
    nucleus (over-counting overestimate).

    For T = 0.07 MeV (D freeze-out, t ~ 200 s) :
        n_HP / n_b ~ alpha_EM^20 * (1000/200) ~ 5 * alpha_EM^20 ~ 2e-42

    Result is utterly negligible compared to the measured D/H ~ 2.5e-5.
    """
    return n_HP_over_n_baryon(T_MeV, c_n=c_n)


# =========================================================================
# 7. Observational benchmarks and chi-square
# =========================================================================

# Observed primordial D/H : Cooke+2018 (gold standard).
DH_OBS_VALUE = 2.527e-5
DH_OBS_ERROR = 0.030e-5
# Standard BBN prediction at Planck eta : PArthENoPE.
DH_STD_VALUE = 2.55e-5
DH_STD_ERROR = 0.03e-5


def chi2_V5_vs_obs(c_n: int = C_VASSILIEV_HP,
                   T_grid: np.ndarray | None = None) -> dict:
    """Chi-square comparison of V5 D/H prediction against observed D/H.

    V5 D/H = (standard PArthENoPE D/H) + DH_shift_from_HP_decay(T_min).
    Compare to Cooke+ 2018 measurement.
    """
    if T_grid is None:
        T_grid = np.logspace(-2, 0, 50)   # 10 keV -> 1 MeV
    dh_shifts = np.array([DH_shift_from_HP_decay(T, c_n=c_n) for T in T_grid])
    # Total D/H (V5) - per-temperature evaluation
    DH_V5 = DH_STD_VALUE * (1.0 + dh_shifts)
    # Sigma : observed error in quadrature with standard prediction error
    sigma = math.hypot(DH_OBS_ERROR, DH_STD_ERROR)
    chi2 = ((DH_V5 - DH_OBS_VALUE) / sigma) ** 2
    return {
        "T_grid": T_grid, "dh_shift": dh_shifts, "DH_V5": DH_V5,
        "chi2": chi2,
        "DH_obs": DH_OBS_VALUE, "DH_obs_err": DH_OBS_ERROR,
        "DH_std": DH_STD_VALUE, "DH_std_err": DH_STD_ERROR,
        "max_chi2": float(np.max(chi2)),
    }


# =========================================================================
# 8. Inverse constraint : observational upper bound on Omega_class_D
# =========================================================================

def observational_upper_bound_on_n_HP() -> float:
    """Conservative observational upper bound on n_HP / n_baryon.

    A shift of |Delta(D/H)| > 2 sigma above the observed error budget
    (sigma ~ 0.04e-5) corresponds to n_HP/n_b > 2*0.04/2.5 = 0.03 ~ 3e-2.
    So the observational ceiling is n_HP/n_b < ~ 3e-3 if we want a < 1-sigma
    perturbation on D/H ; we adopt this as the constraint.
    """
    return 3e-3


def v5_below_observational_bound(c_n: int = C_VASSILIEV_HP) -> dict:
    """Compute how many orders of magnitude V5 falls below the obs bound."""
    n_V5_peak = n_HP_over_n_baryon(T_BBN_START_MEV, c_n=c_n)
    n_obs_bound = observational_upper_bound_on_n_HP()
    log10_ratio = math.log10(n_V5_peak / n_obs_bound) if n_V5_peak > 0 else -np.inf
    return {
        "n_V5_peak_HP_over_baryon": n_V5_peak,
        "n_obs_upper_bound": n_obs_bound,
        "log10_ratio": log10_ratio,           # negative -> V5 below bound
        "headroom_dex": -log10_ratio,         # positive -> orders of slack
    }


