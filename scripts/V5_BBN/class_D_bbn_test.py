        + "=" * 50 + "\n"
        f"Vassiliev exponent c_n           : {vd['c_n_vassiliev']}\n"
        f"Vassiliev factor alpha_EM^{{c_n}}  : "
        f"{vd['vassiliev_factor']:.2e}\n"
        f"n_HP/n_b peak (T = 1 MeV)        : "
