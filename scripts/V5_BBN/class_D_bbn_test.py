# 9. Verdict
# =========================================================================

def verdict() -> dict:
    """Build the global verdict on V5 Class-D vs BBN D/H."""
    cls_D = class_D_heavy_proton_plasma()
    # Peak Class-D abundance (at BBN start, T = 1 MeV)
    n_V5_peak = n_HP_over_n_baryon(T_BBN_START_MEV)
    # Delta N_eff
    dN_eff = delta_N_eff_HP(T_BBN_START_MEV)
    # D/H shift at D freeze-out (T ~ 70 keV)
    dh_shift = DH_shift_from_HP_decay(T_MeV=0.07)
    # Chi2 vs Cooke+ 2018
    chi2_res = chi2_V5_vs_obs()
    bound_res = v5_below_observational_bound()

    # Verdict logic :
    # - V5 D/H shift << 1e-30 means V5 = standard BBN to machine precision.
    # - This is INDISTINCT TRIVIAL by construction (Vassiliev kills it).
    if dh_shift < 1e-10 and dN_eff < 1e-10:
        v = ("INDISTINCT TRIVIAL : V5 Class-D abundance n_HP/n_b "
             f"= {n_V5_peak:.2e} at BBN start ; Delta(D/H) "
             f"= {dh_shift:.2e} ; Delta N_eff = {dN_eff:.2e}. "
             f"V5 reproduces standard PArthENoPE BBN to {bound_res['headroom_dex']:.0f} dex below "
             "the observational bound. Vassiliev suppression "
             "alpha_EM^{c_n} kills any signal.")
    elif dh_shift < DH_OBS_ERROR / DH_OBS_VALUE:
        v = "CONTRIBUTES (small shift below observational sensitivity)"
    elif dh_shift < 0.5:
        v = "TENSION (shift comparable to D/H sensitivity)"
    else:
        v = "REFUTED (HP plasma shift exceeds observed D/H)"

    return {
        "class_D_name": cls_D.name,
        "c_n_vassiliev": C_VASSILIEV_HP,
        "vassiliev_factor": vassiliev_suppression_HP(),
        "n_HP_over_n_b_peak": n_V5_peak,
        "delta_N_eff": dN_eff,
        "DH_shift_at_freezeout": dh_shift,
        "DH_V5_central": DH_STD_VALUE * (1.0 + dh_shift),
        "DH_observed": DH_OBS_VALUE,
        "DH_std_prediction": DH_STD_VALUE,
        "chi2_max": chi2_res["max_chi2"],
        "obs_upper_bound_n_HP_over_b": bound_res["n_obs_upper_bound"],
        "log10_V5_below_bound": -bound_res["log10_ratio"],
        "verdict": v,
    }


