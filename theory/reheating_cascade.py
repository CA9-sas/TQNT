# ---------------------------------------------------------------------------
# V5.17 constants.
# ---------------------------------------------------------------------------

# Crossings of the unknot 0_1: zero by definition.
C_N_UNKNOT = 0

# Stage-1 decay prefactor; O(1) Chern-Simons matrix element for the
# unknot Wilson loop. Jones(0_1) = 1 exactly (Witten 1989).
PREFACTOR_STAGE1 = 1.0

# Radiation EoS during Stage 1 reheating (instantaneous 0_1 decay):
# the universe enters radiation domination right at H_end.
W_REH_V5p17 = 1.0 / 3.0


# ---------------------------------------------------------------------------
# 1. Stage-1 decay rate: chi -> 0_1 modes.
# ---------------------------------------------------------------------------
def Gamma_reh_stage1_unknot(H_end_GeV: float,
                            prefactor: float = PREFACTOR_STAGE1) -> float:
    """V5.17 Stage-1 decay rate via the unknot 0_1 channel.

        Gamma_stage1 = prefactor * alpha_EM^{c_n=0} * H_end = prefactor * H_end

    Because c_n(0_1) = 0, the Vassiliev suppression alpha_EM^{c_n}
    that crippled the V5.16 prediction (alpha_EM^{18} ~ 1e-39) reduces
    to unity. The chi-field decays into 0_1 modes (primordial photons)
    at essentially the Hubble rate.

    Parameters
    ----------
    H_end_GeV : float
        Hubble rate at end of slow-roll inflation, GeV.
    prefactor : float
        O(1) Chern-Simons matrix element. Default 1 (Jones(0_1)=1 in
        Witten's normalization, no SU(2)_135 form-factor).

    Returns
    -------
    Gamma : float
        Stage-1 decay rate in GeV.
    """
    if H_end_GeV <= 0:
        raise ValueError(f"H_end must be positive, got {H_end_GeV}")
    return prefactor * (ALPHA_EM ** C_N_UNKNOT) * H_end_GeV


def Gamma_reh_stage2_nucleon(H_end_GeV: float,
                             c_n_eff: int = C_N_NUCLEON_EFF,
                             prefactor: float = 1.0) -> float:
    """V5.17 Stage-2 nominal rate (kept for comparison with V5.16).

    Stage 2 (0_1 -> SM nucleons) is set kinematically by SM gauge
    equilibration rates at T_high, NOT by the chi-decay vertex.
    We retain the alpha_EM^{c_n} expression only for documentation:
    it is the rate at which any *direct* (chi -> nucleon) channel
    would proceed, and it is too slow to matter -- but Stage 2 is
    instead driven by gauge processes in the 0_1 bath.

    Returns
    -------
    Gamma : float
        Direct chi -> nucleon rate in GeV (sub-dominant, kept for ref.).
    """
    return prefactor * (ALPHA_EM ** c_n_eff) * H_end_GeV


# ---------------------------------------------------------------------------
# 2. Stage-1 reheating temperature T_high.
# ---------------------------------------------------------------------------
def T_high_after_stage1(H_end_GeV: float | None = None,
                        prefactor: float = PREFACTOR_STAGE1,
                        g_star: float = G_STAR_SM,
                        eps_top: float = EPS_TOP_DEFAULT,
                        beta: float = BETA_TOP_DEFAULT) -> float:
    """V5.17 reheating temperature after Stage 1 (instantaneous 0_1 decay).

    The end of Stage 1 occurs when H ~ Gamma_stage1 ~ H_end, so the
    universe enters radiation domination essentially at H = H_end.
    All the inflation energy density rho_end is converted into a
    relativistic 0_1 (photon) bath:

        rho_reh = rho_end = 3 (H_end M_pl)^2
        T_high  = (30 rho_end / (pi^2 g_*))^{1/4}.

    Equivalently, since Gamma_stage1 = H_end, the Liddle-Leach
    formula reduces to T_reh = (90/(pi^2 g_*))^{1/4} sqrt(H_end M_pl).

    Parameters
    ----------
    H_end_GeV : float, optional
        Hubble at end of inflation. If None, derived from V5.14.
    prefactor : float
        Stage-1 O(1) prefactor.
    g_star : float
        Effective relativistic dof (default 106.75 = full SM).

    Returns
    -------
    T_high : float (GeV).
    """
    if H_end_GeV is None:
        H_end_GeV = H_end_V5p14(eps_top=eps_top, beta=beta)
    Gamma1 = Gamma_reh_stage1_unknot(H_end_GeV, prefactor=prefactor)
    # rho_reh = 3 (Gamma_stage1 M_pl)^2 (in GeV^4)
    rho_reh_GeV4 = 3.0 * (Gamma1 * M_PL_REDUCED_GEV) ** 2
    return float((30.0 * rho_reh_GeV4 / (math.pi ** 2 * g_star)) ** 0.25)


def T_reh_after_thermalization(H_end_GeV: float | None = None,
                               prefactor: float = PREFACTOR_STAGE1,
                               g_star: float = G_STAR_SM,
                               eps_top: float = EPS_TOP_DEFAULT,
                               beta: float = BETA_TOP_DEFAULT) -> float:
    """V5.17 reheating temperature after the *full* 2-stage cascade.

    Stage 2 (0_1 -> SM nucleons + leptons) is kinetic at T_high >>
    T_QCD ~ 0.2 GeV: SU(3) thermal equilibration runs at
    Gamma_th ~ alpha_s^2 T >> H(T_high). The full SM thermalizes
    on a timescale much shorter than 1/H, so the radiation-dominated
    temperature after thermalization equals T_high to <1% accuracy
    (the small correction is the change in g_* if some species are
    not yet relativistic; we set g_* = G_STAR_SM ~ 106.75 as a
    high-temperature default).

    Returns
    -------
    T_reh : float (GeV) -- effectively equal to T_high in V5.17.
    """
    return T_high_after_stage1(H_end_GeV=H_end_GeV, prefactor=prefactor,
                               g_star=g_star, eps_top=eps_top, beta=beta)


# ---------------------------------------------------------------------------
# 3. N_e prediction with V5.17 cascade.
# ---------------------------------------------------------------------------
def N_e_V5p17(eps_top: float = EPS_TOP_DEFAULT,
              beta: float = BETA_TOP_DEFAULT,
              phi_max: float = PHI_MAX_V5p13,
              prefactor: float = PREFACTOR_STAGE1,
              g_star: float = G_STAR_SM,
              N_pivot_LL: float = N_PIVOT_LL,
              N_e_seed: float = N_EFOLDS_PIVOT) -> float:
    """V5.17 N_e at the Planck pivot k_* = 0.05 Mpc^-1.

    Liddle-Leach formula with w_reh = 1/3 (Stage-1 instantaneous):

        N_e = N_pivot_LL
              + (1/4) ln(V_* / M_pl^4)
              + (1/4) ln(V_* / rho_end)
              + 0                              (w_reh = 1/3)

    Stage 2 does not contribute because the universe is already
    radiation-dominated at the end of Stage 1.

    Parameters
    ----------
    eps_top, beta, phi_max : V5.14 potential parameters.
    prefactor : O(1) Chern-Simons prefactor (only affects log via T_reh,
        and since the reheating term vanishes for w_reh = 1/3 the
        prefactor drops out of N_e).
    g_star : effective relativistic dof.
    N_pivot_LL : Liddle-Leach pivot constant.
    N_e_seed : seed N_e used for V5.14 V_0 calibration.

    Returns
    -------
    N_e : float (e-folds).
    """
    phi_star = find_phi_pivot_V5p14(N_e_target=N_e_seed, eps_top=eps_top,
                                    beta=beta, phi_max=phi_max)
    V0 = V0_calibrated_V5p14(N_e=N_e_seed, eps_top=eps_top, beta=beta,
                             phi_max=phi_max)
    V_star = float(V_total_V5p14(phi_star, V0=V0, eps_top=eps_top, beta=beta,
                                 phi_max=phi_max))
    rho_end = rho_end_V5p14(eps_top=eps_top, beta=beta, phi_max=phi_max,
                            N_e_target=N_e_seed)

    # w_reh = 1/3 -> reheating term = 0 in the LL formula.
    ln_Vstar_Mpl = math.log(V_star)
    ln_Vstar_over_rho_end = math.log(V_star / rho_end)
    return float(N_pivot_LL
                 + 0.25 * ln_Vstar_Mpl
                 + 0.25 * ln_Vstar_over_rho_end)


# ---------------------------------------------------------------------------
# 4. Re-derived CMB observables n_s, r at N_e^{V5.17}.
# ---------------------------------------------------------------------------
def n_s_r_recomputed(N_e: float) -> tuple[float, float]:
    """Starobinsky (V5.14 limit eps_top -> 0) recomputed at given N_e.

        n_s = 1 - 2/N_e
        r   = 12 / N_e^2

    Parameters
    ----------
    N_e : float
        e-fold number at the pivot.

    Returns
    -------
    (n_s, r) : tuple of floats.
    """
    if N_e <= 0:
        raise ValueError(f"N_e must be positive, got {N_e}")
    n_s = 1.0 - 2.0 / N_e
    r = 12.0 / N_e ** 2
    return float(n_s), float(r)


# ---------------------------------------------------------------------------
# 5. Full V5.17 cascade prediction.
# ---------------------------------------------------------------------------
@dataclass
class CascadeReheatingV5p17:
    """V5.17 two-stage cascade reheating prediction."""
    # V5.14 inputs
    eps_top: float
    beta: float
    phi_max: float
    # Stage-1 quantities (0_1 channel)
    H_end_GeV: float
    Gamma_stage1_GeV: float
    suppression_stage1: float        # alpha_EM^{c_n=0} = 1
    # Stage-2 quantities (nominal nucleon channel, sub-dominant)
    Gamma_stage2_direct_GeV: float
    suppression_stage2: float        # alpha_EM^{18}
    # Temperatures
    T_high_GeV: float                # after Stage 1
    T_reh_GeV: float                 # after Stage 2 thermalization
    # e-folds and CMB
    w_reh: float                     # = 1/3
    N_e_V5p17: float
    n_s_V5p17: float
    r_V5p17: float
    # Compatibilities
    BBN_compatible: bool
    Planck_compatible: bool
    BICEP_compatible: bool
    n_s_deviation_sigma: float


def predict_cascade_V5p17(eps_top: float = EPS_TOP_DEFAULT,
                          beta: float = BETA_TOP_DEFAULT,
                          phi_max: float = PHI_MAX_V5p13,
                          prefactor: float = PREFACTOR_STAGE1,
                          c_n_stage2: int = C_N_NUCLEON_EFF,
                          g_star: float = G_STAR_SM,
                          N_pivot_LL: float = N_PIVOT_LL,
                          N_e_seed: float = N_EFOLDS_PIVOT
                          ) -> CascadeReheatingV5p17:
    """Compute the full V5.17 cascade prediction."""
    H_end_GeV = H_end_V5p14(eps_top=eps_top, beta=beta, phi_max=phi_max,
                            N_e_target=N_e_seed)
    Gamma1 = Gamma_reh_stage1_unknot(H_end_GeV, prefactor=prefactor)
    Gamma2 = Gamma_reh_stage2_nucleon(H_end_GeV, c_n_eff=c_n_stage2)
    T_high = T_high_after_stage1(H_end_GeV=H_end_GeV, prefactor=prefactor,
                                 g_star=g_star, eps_top=eps_top, beta=beta)
    T_reh = T_reh_after_thermalization(H_end_GeV=H_end_GeV,
                                       prefactor=prefactor, g_star=g_star,
                                       eps_top=eps_top, beta=beta)
    N_e = N_e_V5p17(eps_top=eps_top, beta=beta, phi_max=phi_max,
                    prefactor=prefactor, g_star=g_star,
                    N_pivot_LL=N_pivot_LL, N_e_seed=N_e_seed)
    n_s, r = n_s_r_recomputed(N_e)
    n_s_dev = (n_s - N_S_PLANCK) / N_S_PLANCK_SIGMA
    return CascadeReheatingV5p17(
        eps_top=eps_top,
        beta=beta,
        phi_max=phi_max,
        H_end_GeV=H_end_GeV,
        Gamma_stage1_GeV=Gamma1,
        suppression_stage1=ALPHA_EM ** C_N_UNKNOT,
        Gamma_stage2_direct_GeV=Gamma2,
        suppression_stage2=ALPHA_EM ** c_n_stage2,
        T_high_GeV=T_high,
        T_reh_GeV=T_reh,
        w_reh=W_REH_V5p17,
        N_e_V5p17=N_e,
        n_s_V5p17=n_s,
        r_V5p17=r,
        BBN_compatible=bool(T_reh > T_REH_BBN_MIN_GEV),
        Planck_compatible=bool(abs(n_s_dev) < 3.0),
        BICEP_compatible=bool(r < R_PLANCK_BICEP),
        n_s_deviation_sigma=float(n_s_dev),
    )


def validate_against_Planck_V5p17(eps_top: float = EPS_TOP_DEFAULT
                                  ) -> dict:
    """Flat-dict summary for tests, plots, LaTeX."""
    pred = predict_cascade_V5p17(eps_top=eps_top)
    return {
        "model": "V5.17 cascade-reheating 2-stage",
        "H_end_GeV": pred.H_end_GeV,
        "Gamma_stage1_GeV": pred.Gamma_stage1_GeV,
        "Gamma_stage2_direct_GeV": pred.Gamma_stage2_direct_GeV,
        "suppression_stage1": pred.suppression_stage1,
        "suppression_stage2": pred.suppression_stage2,
        "T_high_GeV": pred.T_high_GeV,
        "T_reh_GeV": pred.T_reh_GeV,
        "T_BBN_min_GeV": T_REH_BBN_MIN_GEV,
        "T_reh_over_T_BBN": pred.T_reh_GeV / T_REH_BBN_MIN_GEV,
        "w_reh": pred.w_reh,
        "N_e_V5p17": pred.N_e_V5p17,
        "N_e_canonical": N_EFOLDS_PIVOT,
        "Delta_N_e": pred.N_e_V5p17 - N_EFOLDS_PIVOT,
        "n_s_V5p17": pred.n_s_V5p17,
        "n_s_Planck": N_S_PLANCK,
        "n_s_Planck_sigma": N_S_PLANCK_SIGMA,
        "n_s_deviation_sigma": pred.n_s_deviation_sigma,
        "r_V5p17": pred.r_V5p17,
        "r_BICEP_upper": R_PLANCK_BICEP,
        "BBN_compatible": pred.BBN_compatible,
        "Planck_compatible": pred.Planck_compatible,
        "BICEP_compatible": pred.BICEP_compatible,
    }


def summary(eps_top: float = EPS_TOP_DEFAULT) -> dict:
    """Alias for validate_against_Planck_V5p17."""
    return validate_against_Planck_V5p17(eps_top=eps_top)
