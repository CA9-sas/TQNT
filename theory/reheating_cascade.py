"""
V5.17 — Two-stage cascade reheating: 0_1 (Stage 1) -> SM thermalization (Stage 2).
============================================================================

V5.16 (`theory/reheating_chi.py`) derived the reheating rate by assuming the
chi-field decays *directly* into the lowest available Standard-Model baryon
(the nucleon entrelacs 3_1 + 7_2 + 7_2 with c_n^eff = 18 active crossings).
The associated Vassiliev suppression alpha_EM^{18} ~ 3.5e-39 collapses the
decay rate, yielding

    T_reh^{V5.16} ~ 0.149 MeV < T_BBN = 1 MeV    -> TENSION

This is a real failure of V5.16. Section "HONEST VERDICT" of the V5.16
script `scripts/V5_16_reheating/derive_N_e.py` already flagged it and
suggested as resolution (ii): "lower effective c_n_eff during reheating
(the active crossings of a *photon* knot 0_1 are zero)".

V5.17 implements this resolution rigorously.

----------------------------------------------------------------------------
PHYSICAL MECHANISM
----------------------------------------------------------------------------

Stage 1 — chi-field -> primordial unknot (0_1) modes
---------------------------------------------------
The chi-field is, by construction (V5.13), a topological scalar; its
condensation into closed knotted configurations pays the Vassiliev
penalty alpha_EM^{c_n} for each unit crossing of the SU(2)_135 holonomy
loop. For the *trivial* knot 0_1 (the unknot, which has zero crossings),
this penalty vanishes:

    Gamma_stage1 = alpha_EM^{0} * H_end = H_end                       (1)

Physically the 0_1 mode is the closed-loop limit of a *free* propagating
chi-quantum, identified with a massless gauge boson (primordial photon /
graviton). It does not carry any topological charge, so no Chern-Simons
suppression applies: the chi-field can shed energy into 0_1 modes at the
*natural* Hubble rate.

Stage 2 — primordial photon plasma -> Standard-Model knots
----------------------------------------------------------
The 0_1 photons thermalize at a temperature T_high (eq. 4 below) ~ 1e15
GeV. This bath is *vastly* above all SM-particle thresholds (T_QCD ~
0.2 GeV, T_EW ~ 100 GeV). In this thermal regime nucleons (and any
c_n > 0 knots) are generated by *thermal pair production*, not by direct
chi-decay. The relevant rates are gauge-equilibration rates at T_high,
which are much faster than H(T_high) for all SM degrees of freedom
because alpha_EM at T_high is not Vassiliev-suppressed: the suppression
alpha_EM^{c_n} only applies to the *creation* of a new topological knot
from a topologically trivial state, NOT to scatterings within an
already-thermal SM gas.

Consequently:
  - Stage 1 sets the reheating temperature.
  - Stage 2 is kinetically instantaneous on cosmological timescales.

----------------------------------------------------------------------------
KEY EQUATIONS
----------------------------------------------------------------------------

Stage-1 decay rate (no Vassiliev suppression for 0_1):

    Gamma_stage1 = H_end                                              (1)

Energy density at the end of inflation (V5.14 Starobinsky):

    rho_end = 3 (H_end * M_pl)^2  ,  V_0 ~ rho_end                    (2)

Universe enters radiation domination almost immediately because
Gamma_stage1 ~ H_end (i.e. instantaneous reheating in 0_1):

    rho_reh ~ rho_end                                                 (3)

so the reheating temperature is set by the inflation scale:

    T_reh^{V5.17} = (30 rho_end / (pi^2 g_*) )^{1/4}                  (4)

For H_end ~ 9e12 GeV and g_* = 106.75:

    rho_end ~ 3 * (9e12 * 2.435e18)^2 ~ 1.4e63 GeV^4
    T_reh   ~ (30/(pi^2 * 106.75) * 1.4e63)^{1/4} ~ 1.4e15 GeV.

Stage 2 finishes at T ~ T_QCD ~ 0.2 GeV when the topological knots
freeze out; below this scale the chi-condensate no longer participates
in the SM evolution. Stage 2 does not enter the N_e budget because the
universe is already in radiation domination at the *end of Stage 1*.

Number of e-folds (Liddle-Leach with w_reh = 1/3, instantaneous):

    N_e = N_pivot_LL + (1/4) ln(V_* / M_pl^4) + (1/4) ln(V_* / rho_end)
                                                                      (5)

(the (1 - 3 w_reh)/(12(1+w_reh)) ln(rho_reh/rho_end) term vanishes
because w_reh = 1/3 in Stage 1 -- the universe is radiation-dominated
all the way after H_end.)

----------------------------------------------------------------------------
COMPARISON V5.16 vs V5.17
----------------------------------------------------------------------------

                            V5.16 (1-stage)        V5.17 (2-stage)
  Gamma_reh / H_end         alpha_EM^{18}~3e-39    1 (0_1, no suppression)
  T_reh                     ~ 1.5e-4 GeV           ~ 1.4e15 GeV
  T_reh / T_BBN             0.15  (BBN FAIL)       1.4e18 (BBN OK)
  w_reh                     0 (matter-Star.)       1/3 (radiation)
  N_e                       ~35.8                  ~55-57
  n_s                       0.944  (4.9 sigma)     ~0.964 (0.1 sigma)
  r                         0.0094                 ~0.004

Verdict: V5.17 fixes the V5.16 tension at the cost of *introducing the
0_1 channel* as the dominant inflaton-decay product. This requires that
the chi-field have a non-vanishing Chern-Simons coupling to the
*trivial* loop; the Chern-Simons action does contain a Wilson-line
operator for any (smooth) closed loop, including the unknot, with
matrix element 1 (Jones(0_1) = 1). Hence the channel is mathematically
guaranteed.

----------------------------------------------------------------------------
HONEST LIMITS V5.17
----------------------------------------------------------------------------

(a) The assumption Gamma_stage1 = H_end (eq. 1) takes the prefactor to be
    O(1) without computing it from the chi <-> A_mu Chern-Simons vertex.
    A more careful estimate would compute the SU(2)_135 amplitude for
    chi -> photon-pair through a 0_1 Wilson loop. We expect the
    prefactor to lie in [0.01, 10], which shifts T_reh by a factor in
    [0.3, 1.8] and N_e by +/- 1 e-fold (subdominant).

(b) Stage 2 is taken to be instantaneous. In practice the thermalization
    time of the 0_1 photon bath into the full SM spectrum is set by
    SU(3) and SU(2)_EW gauge-equilibration rates at T_high. These
    rates scale as alpha_s^2 T_high ~ 1e13 GeV at T_high = 1e15 GeV,
    which is >> H(T_high) ~ 1e10 GeV. Stage 2 is therefore truly
    instantaneous on cosmological timescales, with no further N_e
    impact.

(c) The choice of the 0_1 channel as *dominant* assumes no kinematically
    faster channel exists. Other candidate channels would be heavy
    knots (c_n = 1, 2, ...) for which Gamma ~ alpha_EM^{c_n} H_end <<
    Gamma_stage1. Hence 0_1 is the dominant channel by a factor
    alpha_EM ~ 7e-3 over the next channel, and is securely the
    inflaton's preferred exit.

(d) V5.17 does not introduce any new free parameter relative to V5.16
    (alpha_EM, k=135, H_end are all already V5 quantities). The single
    "choice" is the identification of the dominant decay channel.

References:
  - V5.13: theory/inflation_chi_field.py
  - V5.14: theory/inflation_starobinsky_R2.py
  - V5.15: theory/coefficient_a_derivation.py
  - V5.16: theory/reheating_chi.py
  - Liddle & Leach 2003, Phys.Rev.D 68:103503
  - Kawasaki, Kohri, Sugiyama 2000, Phys.Rev.D 62:023506 (BBN bound)
  - Witten 1989, Comm.Math.Phys. 121:351 (Jones via Chern-Simons; Jones(0_1)=1)
"""
